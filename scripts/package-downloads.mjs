import {copyFile,mkdir,readFile,writeFile} from 'node:fs/promises';
import {createHash} from 'node:crypto';
import {spawnSync} from 'node:child_process';
import {fileURLToPath} from 'node:url';
import path from 'node:path';
const root=fileURLToPath(new URL('../',import.meta.url));
const output=path.join(root,'artifacts','downloads');
await mkdir(output,{recursive:true});
const apk='OcheClub-1.0.0-debug.apk',web='OcheClub-web.zip';
await copyFile(path.join(root,'android/app/build/outputs/apk/debug/app-debug.apk'),path.join(output,apk));
const zip=spawnSync('python3',['-c','import shutil,sys; shutil.make_archive(sys.argv[1], "zip", sys.argv[2])',path.join(output,'OcheClub-web'),path.join(root,'dist')],{stdio:'inherit'});
if(zip.status!==0)throw new Error('Web archive creation failed');
const checksums=[];
for(const name of [apk,web])checksums.push(createHash('sha256').update(await readFile(path.join(output,name))).digest('hex')+'  '+name);
await writeFile(path.join(output,'SHA256SUMS.txt'),checksums.join('\n')+'\n');
console.log('Prepared debug test APK, web ZIP and SHA256SUMS.txt in artifacts/downloads/.');
